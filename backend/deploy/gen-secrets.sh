#!/usr/bin/env bash
# Generate production secrets + the audit signing key for docker-compose.prod.yml.
# Run once from backend/ BEFORE the first `docker compose ... up`. Writes:
#   - .env.prod                      env file consumed by compose (gitignored — secrets)
#   - deploy/keys/audit_ed25519.key  PEM PKCS8 ed25519 audit signing key (gitignored)
# Re-running refuses to overwrite; remove the files first to regenerate.
set -euo pipefail
cd "$(dirname "$0")/.."   # -> backend/

ENV_FILE=".env.prod"
KEY_DIR="deploy/keys"
KEY_FILE="${KEY_DIR}/audit_ed25519.key"

command -v openssl >/dev/null 2>&1 || { echo "error: openssl is required" >&2; exit 1; }
if [[ -e "$ENV_FILE" || -e "$KEY_FILE" ]]; then
  echo "error: $ENV_FILE or $KEY_FILE already exists; remove them first to regenerate." >&2
  exit 1
fi

mkdir -p "$KEY_DIR"

# Hex (URL-safe) so the DSN needs no percent-encoding.
POSTGRES_PASSWORD="$(openssl rand -hex 24)"
CREDENTIAL_KEY_B64="$(openssl rand -base64 32)"     # 32 bytes for AEAD credential encryption
SESSION_KEY_B64="$(openssl rand -base64 48)"        # >=32 bytes for session signing
ADMIN_BOOTSTRAP_TOKEN="hk_admin_$(openssl rand -hex 24)"

# ed25519 audit signing key in PEM PKCS8 — accepted by the gateway's
# parseAuditPrivateKey (cmd/gateway/config.go).
openssl genpkey -algorithm ed25519 -out "$KEY_FILE" >/dev/null 2>&1
chmod 600 "$KEY_FILE"

umask 077
cat > "$ENV_FILE" <<EOF
# Generated by deploy/gen-secrets.sh — DO NOT COMMIT. Production secrets.
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
HUAKAI_DATABASE_URL=postgres://huakai:${POSTGRES_PASSWORD}@postgres:5432/huakai?sslmode=disable
HUAKAI_CREDENTIAL_KEY_B64=${CREDENTIAL_KEY_B64}
HUAKAI_SESSION_SIGNING_KEY_B64=${SESSION_KEY_B64}
HUAKAI_ADMIN_BOOTSTRAP_TOKEN=${ADMIN_BOOTSTRAP_TOKEN}
HUAKAI_RELEASE_MODE=production
# Self-service registration is OFF by default in production.
# Set to open or invite_required to allow signups.
HUAKAI_USER_REGISTRATION_MODE=disabled
EOF
chmod 600 "$ENV_FILE"

echo "Wrote ${ENV_FILE} and ${KEY_FILE} (both chmod 600, gitignored)."
echo "One-time admin bootstrap token (use once, then rotate): ${ADMIN_BOOTSTRAP_TOKEN}"
